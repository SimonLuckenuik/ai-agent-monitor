"""Writes the headers scripts/build_options.py generates for a PlatformIO build.

    python3 emulator/gen_headers.py <project dir> <output dir>

Same content as the firmware build (scripts/sys_files.py): the settings page as the
files an update brings, the setup page in web_fallback.h, files_hash.h; plus a build ID
in build_info.h, and an empty wifi_secrets.h (the emulator is always "connected").

One emulator-only addition to both pages: opened as /#password=<password>, it
signs in, takes the password out of the address bar and reloads. The screen page's
"Settings page" button links there. The fragment never reaches the server, and a
firmware build (scripts/build_options.py) never includes this.
"""
import datetime
import os
import re
import sys

root, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)

AUTO_SIGN_IN = b"""<script>(()=>{const m=location.hash.match(/[#&]password=([^&]*)/);if(!m)return;
history.replaceState(null,"",location.pathname+location.search);
fetch("/api/auth/login",{method:"POST",body:new URLSearchParams({password:decodeURIComponent(m[1])})})
.then(r=>{if(r.ok)location.reload()})})()</script>
"""

sys.path.insert(0, os.path.join(root, "scripts"))
import sys_files   # noqa: E402 - the firmware build's own (spec 048): page, setup page, hash
import make_update   # noqa: E402

# The settings page as the files an update brings (/sys), the setup page in flash, and
# FILES_HASH; both pages get the sign-in script. emu_sys_files.h carries the files so the
# emulator can put them in its storage at start (emulator.cpp, EMU_SEED_FILES).
files, line = sys_files.build(root, out, os.path.join(out, "sys"), AUTO_SIGN_IN, jsonrender=True)   # the emulator has json-render (spec 047)
print("gen_headers: " + line)
parts = ["#pragma once", "// Generated by emulator/gen_headers.py: the files an update brings (spec 048).",
         "#include <stddef.h>", "#include <stdint.h>",
         "struct EmuSysFile { const char* name; const uint8_t* data; size_t size; };"]
for i, (name, data) in enumerate(files):
    rows = [", ".join("0x%02x" % b for b in data[j:j + 20]) for j in range(0, len(data), 20)]
    parts.append("static const uint8_t EMU_SYS_%d[] = {\n%s\n};" % (i, ",\n".join("  " + r for r in rows)))
parts.append("static const EmuSysFile EMU_SYS_FILES[] = {%s};" % ", ".join(
    '{"%s", EMU_SYS_%d, %d}' % (name, i, len(data)) for i, (name, data) in enumerate(files)))
parts.append('static const char EMU_SYS_MANIFEST[] = "%08x";' % make_update.files_hash(files))
sys_files.write_if_changed(os.path.join(out, "emu_sys_files.h"), "\n".join(parts) + "\n")

build = "emulator %s" % datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
release = re.search(r'#define FW_VERSION "([^"]+)"', open(os.path.join(root, "src", "main.cpp"), encoding="utf-8").read()).group(1)
with open(os.path.join(out, "build_info.h"), "w", newline="\n") as f:
    f.write('#pragma once\n#define FW_BUILD "%s"\n#define FW_RELEASE "%s"\n' % (build, release))
with open(os.path.join(out, "wifi_secrets.h"), "w", newline="\n") as f:
    f.write("#pragma once\n")

# platformio.ini's [env:esp12e] build_flags (-D ...) and board_build.f_cpu, force-included
# into every emulator source: the real TFT_eSPI gets the clock's panel config, and the
# emulator's drawing speed follows the CPU frequency (panel.cpp).
section, flags, f_cpu, in_flags = None, [], "80000000L", False
with open(os.path.join(root, "platformio.ini"), encoding="utf-8") as ini:
    for line in ini:
        code = line.split(";", 1)[0].rstrip()
        m = re.match(r"\[(.+)\]", code)
        if m:
            section, in_flags = m.group(1), False
            continue
        if section != "env:esp12e":
            continue
        m = re.match(r"([\w.]+)\s*=\s*(.*)", code)
        if m:
            in_flags = m.group(1) == "build_flags"
            if m.group(1) == "board_build.f_cpu":
                f_cpu = m.group(2).strip()
            code = m.group(2) if in_flags else ""
        elif not line[:1].isspace():
            in_flags = False
        if in_flags:
            flags += re.findall(r"-D\s*(\w+)(?:=(\S+))?", code)   # mDNS too: our responder runs on the host core
with open(os.path.join(out, "emu_build_flags.h"), "w", newline="\n") as f:
    f.write("#pragma once\n// Generated by emulator/gen_headers.py from platformio.ini. Do not edit.\n")
    for name, value in flags:
        f.write("#ifndef %s\n#define %s %s\n#endif\n" % (name, name, value or "1"))
    f.write("#undef F_CPU\n#define F_CPU %s\n" % f_cpu)
print("gen_headers: build '%s'; %d build flags, F_CPU %s"
      % (build, len(flags), f_cpu))
