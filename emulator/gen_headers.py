"""Writes the headers scripts/build_options.py generates for a PlatformIO build.

    python3 emulator/gen_headers.py <project dir> <output dir>

Same content as the firmware build: web/index.html gzipped into web_index.h, a build ID
in build_info.h, and an empty wifi_secrets.h (the emulator is always "connected").

One emulator-only addition to the settings page: opened as /#password=<password>, it
signs in, takes the password out of the address bar and reloads. The screen page's
"Settings page" button links there. The fragment never reaches the server, and a
firmware build (scripts/build_options.py) never includes this.
"""
import datetime
import gzip
import os
import sys

root, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)

AUTO_SIGN_IN = b"""<script>(()=>{const m=location.hash.match(/[#&]password=([^&]*)/);if(!m)return;
history.replaceState(null,"",location.pathname+location.search);
fetch("/api/auth/login",{method:"POST",body:new URLSearchParams({password:decodeURIComponent(m[1])})})
.then(r=>{if(r.ok)location.reload()})})()</script>
"""

with open(os.path.join(root, "web", "index.html"), "rb") as f:
    html = f.read()
if b"</head>" not in html:
    sys.exit("gen_headers: web/index.html has no </head> for the emulator's sign-in script")
html = html.replace(b"</head>", AUTO_SIGN_IN + b"</head>", 1)
packed = gzip.compress(html, compresslevel=9, mtime=0)
rows = [", ".join("0x%02x" % b for b in packed[i:i + 20]) for i in range(0, len(packed), 20)]
with open(os.path.join(out, "web_index.h"), "w", newline="\n") as f:
    f.write("\n".join([
        "#pragma once",
        "// Generated by emulator/gen_headers.py from web/index.html. Do not edit.",
        "#include <Arduino.h>",
        "static const size_t INDEX_HTML_GZ_LEN = %d;" % len(packed),
        "static const uint8_t INDEX_HTML_GZ[] PROGMEM = {",
        ",\n".join("  " + r for r in rows),
        "};", ""]))

build = "emulator %s" % datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
with open(os.path.join(out, "build_info.h"), "w", newline="\n") as f:
    f.write('#pragma once\n#define FW_BUILD "%s"\n' % build)
with open(os.path.join(out, "wifi_secrets.h"), "w", newline="\n") as f:
    f.write("#pragma once\n")
print("gen_headers: web/index.html -> %d bytes gzipped, build '%s'" % (len(packed), build))
