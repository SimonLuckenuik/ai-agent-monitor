"""Compiles the digit outlines of Bebas Neue and Outfit (spec 031) into src/outline_glyphs.h.

    python scripts/gen_outline_glyphs.py <smalltv-pomodoro checkout>

The outlines come from smalltv-pomodoro (github.com/davicorrea0/smalltv-pomodoro, GPL-3.0):
Bebas Neue's in smalltv-pomodoro/face_flip.cpp (FLIP_*), Outfit SemiBold's in fonts.cpp
(OUTFIT_*), both already flattened to points on a 720-unit-tall cell. The fonts are under
the SIL Open Font License 1.1 (licenses/BebasNeue-OFL.txt, licenses/Outfit-OFL.txt).
Here each point becomes two bytes on a 255-step grid of the cell's height (at 120 px a step
is under half a pixel). Digits 0-9 and ':'.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "outline_glyphs.h"
FONTS = [("BEBAS", "face_flip.cpp", "FLIP", "BEBAS"), ("OUTFIT", "fonts.cpp", "OUTFIT", "OUTFIT")]


def array(src, name):
    m = re.search(r"\b" + name + r"\s*(?:\[[^\]]*\])+\s*PROGMEM\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    return [int(v) for v in re.findall(r"-?\d+", m.group(1))]


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    base = pathlib.Path(sys.argv[1])
    out = ["// Generated by scripts/gen_outline_glyphs.py from smalltv-pomodoro's outlines: do not edit.",
           "// Bebas Neue (Dharma Type) and Outfit SemiBold (The Outfit Project Authors), digits 0-9 and ':',",
           "// SIL Open Font License 1.1 (licenses/). Points: x, y on a 255-step grid of the digit height.",
           "#pragma once", "#include <stdint.h>", "",
           "struct OutlineFont {",
           "  const uint8_t* pts;     // x, y per point",
           "  const uint8_t* clen;    // points per contour",
           "  const uint8_t* gcont;   // first contour of each glyph (0-9, ':'), then the end",
           "  const uint16_t* gpt;    // first point of each glyph",
           "  const uint8_t* adv;     // advance of each glyph, in 255ths of the height",
           "};", ""]
    total = 0
    for font, file, pts_name, meta in FONTS:
        src = (base / "smalltv-pomodoro" / file).read_text(encoding="utf-8")
        pts = array(src, pts_name + "_PT")
        cend = array(src, (pts_name if pts_name != "OUTFIT" else "OUTFIT") + "_CEND")
        glyph = array(src, meta + "_GLYPH")
        adv = array(src, meta + "_ADV")
        xs, ys = pts[0::2], pts[1::2]
        q = lambda v: max(0, min(255, round(v * 255 / 720)))
        if min(xs + ys) < -20 or max(ys) > 740:
            raise SystemExit(f"{font}: points out of the cell: {min(xs + ys)}..{max(xs + ys)}")
        clen = [cend[0]] + [cend[i] - cend[i - 1] for i in range(1, len(cend))]
        if max(clen) > 255:
            raise SystemExit(f"{font}: a contour of {max(clen)} points")
        gpt = [0 if g == 0 else cend[g - 1] for g in glyph]
        data = [v for x, y in zip(xs, ys) for v in (q(x), q(y))]
        rows = lambda vals, n: ["  " + ", ".join(str(v) for v in vals[i:i + n]) + "," for i in range(0, len(vals), n)]
        f = font.lower()
        out += [f"const uint8_t {font}_PTS[] PROGMEM = {{", *rows(data, 24), "};",
                f"const uint8_t {font}_CLEN[] PROGMEM = {{", *rows(clen, 24), "};",
                f"const uint8_t {font}_GCONT[] PROGMEM = {{", *rows(glyph, 24), "};",
                f"const uint16_t {font}_GPT[] PROGMEM = {{", *rows(gpt, 24), "};",
                f"const uint8_t {font}_ADV[] PROGMEM = {{", *rows([q(a) for a in adv], 24), "};",
                f"const OutlineFont FONT_{font} = {{{font}_PTS, {font}_CLEN, {font}_GCONT, {font}_GPT, {font}_ADV}};", ""]
        size = len(data) + len(clen) + len(glyph) + 2 * len(gpt) + len(adv)
        total += size
        print(f"{font}: {len(xs)} points, {len(clen)} contours, {size} B")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {total} B of tables")


if __name__ == "__main__":
    main()
