# PlatformIO pre-script: optional build-time WiFi defaults and an OTA size guard.
import configparser
import gzip
import os

Import("env")  # noqa: F821 (provided by PlatformIO/SCons)

# ---- Optional WiFi defaults from the gitignored secrets.ini (see secrets.example.ini).
# Written to a generated header with every non-alphanumeric byte octal-escaped, so any
# SSID/password characters survive (command-line -D quoting does not handle backslashes).
def c_string(value):
    return '"' + "".join(chr(b) if b < 0x80 and chr(b).isalnum() else "\\%03o" % b
                         for b in value.encode("utf-8")) + '"'


secrets = os.path.join(env.subst("$PROJECT_DIR"), "secrets.ini")
generated = os.path.join(env.subst("$BUILD_DIR"), "generated")
os.makedirs(generated, exist_ok=True)
lines = ["#pragma once", "// Generated by scripts/build_options.py. Do not edit."]
# SMARTCLOCK_RELEASE=1 (scripts/make_release.py) ignores secrets.ini entirely.
if os.path.isfile(secrets) and os.environ.get("SMARTCLOCK_RELEASE") != "1":
    parser = configparser.ConfigParser(interpolation=None)
    parser.read(secrets, encoding="utf-8")
    ssid = parser.get("wifi", "ssid", fallback="").strip()
    if ssid:
        password = parser.get("wifi", "password", fallback="")
        lines += ["#define DEFAULT_WIFI_SSID " + c_string(ssid),
                  "#define DEFAULT_WIFI_PASS " + c_string(password)]
        print("build_options: default WiFi '%s' from secrets.ini" % ssid)
def write_if_changed(path, content):   # unchanged headers keep their timestamps
    if not os.path.isfile(path) or open(path, encoding="utf-8").read() != content:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)


write_if_changed(os.path.join(generated, "wifi_secrets.h"), "\n".join(lines) + "\n")

# ---- Build ID: git commit, "+" when the tree has uncommitted changes, and build time,
# so two builds of the same version can be told apart on the clock's System card.
import datetime
import subprocess


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=env.subst("$PROJECT_DIR"), capture_output=True,
                              text=True, timeout=10).stdout.strip()
    except Exception:
        return ""


commit = git("rev-parse", "--short", "HEAD") or "nogit"
dirty = "+" if git("status", "--porcelain", "--untracked-files=no") else ""
build_id = "%s%s %s" % (commit, dirty, datetime.datetime.now().strftime("%Y-%m-%d %H:%M"))
write_if_changed(os.path.join(generated, "build_info.h"),
                 '#pragma once\n// Generated by scripts/build_options.py.\n#define FW_BUILD "%s"\n' % build_id)
print("build_options: build %s" % build_id)

# ---- Settings page: web/index.html, gzipped into PROGMEM. The page is self-contained
# (no external fonts or scripts) because it must work on the offline setup AP.
page = os.path.join(env.subst("$PROJECT_DIR"), "web", "index.html")
with open(page, "rb") as f:
    html = f.read()
packed = gzip.compress(html, compresslevel=9, mtime=0)   # mtime=0: reproducible
rows = [", ".join("0x%02x" % b for b in packed[i:i + 20]) for i in range(0, len(packed), 20)]
write_if_changed(os.path.join(generated, "web_index.h"), "\n".join([
    "#pragma once",
    "// Generated by scripts/build_options.py from web/index.html. Do not edit.",
    "#include <Arduino.h>",
    "static const size_t INDEX_HTML_GZ_LEN = %d;" % len(packed),
    "static const uint8_t INDEX_HTML_GZ[] PROGMEM = {",
    ",\n".join("  " + r for r in rows),
    "};", ""]))
print("build_options: web/index.html %d bytes -> %d gzipped" % (len(html), len(packed)))
env.Append(CPPPATH=[generated])

# ---- Size guard and the compressed image. The stock layout (4m3m, matched by
# platformio.ini) leaves 1 MB (AREA) for the running sketch plus the staged OTA copy.
# Plain .bin: the image must fit twice, sector-rounded, with the updater's one-sector
# margin; 0x7e000 keeps a sector of slack below that. (The first flash through the
# stock updater allows ~0x87000: 1 MB - stock's 0x78000.)
# Compressed .bin.gz (include/firmware_validation.h): the running sketch plus the
# staged gzip file must fit, and the bootloader unpacks the image from address 0 up to
# the staged copy, so the image plus the gzip file must fit the area; two sectors of
# slack. A clock needs a firmware that knows the format before it takes a .bin.gz.
MAX_IMAGE = 0x7E000
AREA = 0x100000
SECTOR = 0x1000


def crc32_elf2bin(data):
    """elf2bin.py's CRC (MSB first, poly 0x04c11db7, no final xor), table-driven."""
    table = []
    for i in range(256):
        c = i << 24
        for _ in range(8):
            c = ((c << 1) ^ 0x04C11DB7) if c & 0x80000000 else (c << 1)
        table.append(c & 0xFFFFFFFF)
    crc = 0xFFFFFFFF
    for b in data:
        crc = ((crc << 8) & 0xFFFFFFFF) ^ table[((crc >> 24) ^ b) & 0xFF]
    return crc


def write_gzip(image, path):
    """A standard gzip file whose header carries the "AM" extra field."""
    import struct
    import zlib
    deflate = zlib.compressobj(9, zlib.DEFLATED, -15)
    body = deflate.compress(image) + deflate.flush()
    body += struct.pack("<II", zlib.crc32(image) & 0xFFFFFFFF, len(image))   # gzip trailer
    size = 28 + len(body)
    head = bytes([0x1F, 0x8B, 8, 4, 0, 0, 0, 0, 2, 3]) + struct.pack("<H", 16) + b"AM" + \
        struct.pack("<HIII", 12, len(image), size, crc32_elf2bin(body))
    with open(path, "wb") as f:
        f.write(head + body)
    return size


def check_size(target, source, env):
    path = target[0].get_abspath()
    size = os.path.getsize(path)
    with open(path, "rb") as f:
        packed = write_gzip(f.read(), path + ".gz")
    rounded = lambda n: (n + SECTOR - 1) // SECTOR * SECTOR
    room = AREA - 2 * SECTOR - rounded(packed)
    print("build_options: firmware.bin %d bytes (plain limit %d, %.0f%% used); firmware.bin.gz %d bytes "
          "(compressed limit %d, %.0f%% used)"
          % (size, MAX_IMAGE, 100.0 * size / MAX_IMAGE, packed, room, 100.0 * rounded(size) / room))
    if rounded(size) > room:
        for p in (path, path + ".gz"):
            os.remove(p)  # never leave an image on disk that cannot be updated again
        print("ERROR: image exceeds the OTA limit; it could not be replaced over the air")
        return 1
    if size > MAX_IMAGE:
        print("WARNING: firmware.bin is too big to update uncompressed: update with firmware.bin.gz,"
              " from a firmware that accepts it (1.4.0 on)")
    return 0


env.AddPostAction("$BUILD_DIR/${PROGNAME}.bin", check_size)
