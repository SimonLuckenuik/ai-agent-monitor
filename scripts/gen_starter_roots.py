"""Writes include/starter_roots.h: the root certificates the starter (spec 048) trusts when
it downloads a release from GitHub, as DER in flash.

    python scripts/gen_starter_roots.py [CA bundle .pem]

The bundle defaults to Python's certifi. GitHub's hosts end their chains at these roots
(checked 2026-11-07 with openssl s_client; specs/048-files-with-the-update/RESEARCH.md):
api.github.com and github.com at USERTrust ECC, release-assets.githubusercontent.com and
*.github.io at ISRG Root X1. Run it again if GitHub moves to another root.
"""
import base64
import os
import re
import sys

ROOTS = [   # (name in the header, the certificate's CN)
    ("USERTRUST_ECC", "USERTrust ECC Certification Authority"),
    ("ISRG_ROOT_X1", "ISRG Root X1"),
]


def main():
    if len(sys.argv) > 1:
        bundle = sys.argv[1]
    else:
        import certifi
        bundle = certifi.where()
    text = open(bundle, encoding="utf-8").read()
    # certifi labels each certificate with a "# Label: ..." line before it.
    blocks = re.findall(r"# Label: \"([^\"]+)\".*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)", text, re.S)
    found = {label: pem for label, pem in blocks}
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = ["#pragma once",
           "// Generated by scripts/gen_starter_roots.py from %s: do not edit." % os.path.basename(bundle),
           "// The roots GitHub's hosts chain to (spec 048): the starter checks downloads against them.",
           "#include <pgmspace.h>"]
    for name, cn in ROOTS:
        pem = found.get(cn)
        if not pem:
            sys.exit("gen_starter_roots: %r is not in %s" % (cn, bundle))
        der = base64.b64decode("".join(pem.splitlines()[1:-1]))
        rows = [", ".join("0x%02x" % b for b in der[i:i + 20]) for i in range(0, len(der), 20)]
        out.append("// %s" % cn)
        out.append("static const uint8_t ROOT_%s[] PROGMEM = {\n%s\n};" % (name, ",\n".join("  " + r for r in rows)))
        out.append("static const size_t ROOT_%s_LEN = %d;" % (name, len(der)))
        print("gen_starter_roots: %s, %d bytes" % (cn, len(der)))
    with open(os.path.join(root, "include", "starter_roots.h"), "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
