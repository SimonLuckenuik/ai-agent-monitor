"""The files that come with an update (spec 048) and the setup page in flash, for
scripts/build_options.py (the firmware) and emulator/gen_headers.py (the emulator).

- /sys/index.html.gz: web/index.html minified and gzipped (spec 036), served from storage;
- web_fallback.h: web/fallback.html, gzipped into flash (FALLBACK_HTML_GZ);
- files_hash.h: FILES_HASH, which /sys/manifest must match for the firmware to use them.
"""
import os

import make_update
import minify_page


def page(root, name, extra_head=b""):
    with open(os.path.join(root, "web", name), "rb") as f:
        html = minify_page.minify(f.read().decode("utf-8")).encode("utf-8")
    if extra_head:
        if b"</head>" not in html:
            raise SystemExit("sys_files: web/%s has no </head>" % name)
        html = html.replace(b"</head>", extra_head + b"</head>", 1)
    return html, minify_page.gzip_page(html)


def write_if_changed(path, content):   # unchanged files keep their timestamps (no rebuild)
    data = content.encode("utf-8") if isinstance(content, str) else content
    if not os.path.isfile(path) or open(path, "rb").read() != data:
        with open(path, "wb") as f:
            f.write(data)


def build(root, generated, sys_dir, extra_head=b""):
    """Writes the headers into generated/ and the files into sys_dir/. Returns the files
    as [(name, bytes)] for the update file, and a line for the build log."""
    os.makedirs(generated, exist_ok=True)
    os.makedirs(sys_dir, exist_ok=True)
    html, index_gz = page(root, "index.html", extra_head)
    files = [("index.html.gz", index_gz)]
    for name, data in files:
        write_if_changed(os.path.join(sys_dir, name), data)
    write_if_changed(os.path.join(generated, "files_hash.h"),
                     "#pragma once\n// Generated by scripts/sys_files.py: the files /sys/manifest must match.\n"
                     "#define FILES_HASH 0x%08xu\n" % make_update.files_hash(files))
    fallback, fallback_gz = page(root, "fallback.html", extra_head)
    rows = [", ".join("0x%02x" % b for b in fallback_gz[i:i + 20]) for i in range(0, len(fallback_gz), 20)]
    write_if_changed(os.path.join(generated, "web_fallback.h"), "\n".join([
        "#pragma once",
        "// Generated by scripts/sys_files.py from web/fallback.html. Do not edit.",
        "#include <Arduino.h>",
        "static const size_t FALLBACK_HTML_GZ_LEN = %d;" % len(fallback_gz),
        "static const uint8_t FALLBACK_HTML_GZ[] PROGMEM = {",
        ",\n".join("  " + r for r in rows),
        "};", ""]))
    log = ("web/index.html minified %d bytes -> %d gzipped (a file); web/fallback.html %d -> %d gzipped (flash)"
           % (len(html), len(index_gz), len(fallback), len(fallback_gz)))
    return files, log
